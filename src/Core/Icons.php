	 * @param string $class Additional CSS class(es).
	 *
	 * @return string SVG markup or empty string if the icon doesn't exist.
	 */
	public static function render( string $name, int $size = 20, string $class = '' ): string {
		$paths = self::$icons[ $name ] ?? null;

		if ( $paths === null ) {
			return '';
		}

		$cssClass = 'mdkit-icon' . ( $class !== '' ? ' ' . esc_attr( $class ) : '' );

		return sprintf(
			'<svg xmlns="http://www.w3.org/2000/svg" width="%1$d" height="%1$d" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="%2$s" aria-hidden="true">%3$s</svg>',
			$size,
			$cssClass,
			$paths,
		);
	}

